const express = require('express');
const router = express.Router();
const { authenticateToken } = require('./auth');
const controller = require('../controllers/clockoutReminderController');
const admin = (req, res, next) => String(req.user && req.user.userType || '').toLowerCase() === 'admin' ? next() : res.status(403).json({ success: false, message: 'Admin access required' });
router.use(authenticateToken);
router.get('/status', controller.status);
router.post('/devices/register', controller.register);
router.post('/devices/refresh', controller.register);
router.delete('/devices/:id', controller.remove);
router.get('/policy', admin, controller.policy);
router.put('/policy', admin, controller.updatePolicy);
router.get('/clock-out-reminder-policy', admin, controller.policy);
router.put('/clock-out-reminder-policy', admin, controller.updatePolicy);
module.exports = router;
